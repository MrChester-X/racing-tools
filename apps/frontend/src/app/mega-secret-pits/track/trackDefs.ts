/** Reverse a closed loop's travel direction: flip the segment order and the
 * points within each so the concatenated centerline runs the other way. Drawing
 * is unaffected — polylines render identically in either direction — so a track
 * built from a reversed loop looks the same but karts move the opposite way. */
function reverseLoop(loop: string[]): string[] {
  return [...loop]
    .reverse()
    .map((seg) =>
      parsePoints(seg)
        .reverse()
        .map(([x, y]) => `${x},${y}`)
        .join(" "),
    );
}

function makeTrack(opts: {
  id: string;
  label: string;
  viewBox: string;
  transform: string;
  labelTransform?: string;
  loop: string[];
  infield?: string;
  startFinish: StartFinish;
}): TrackDef {
  const centerline = buildCenterline(opts.loop.flatMap(parsePoints));
  const midX = (opts.startFinish.x1 + opts.startFinish.x2) / 2;
  const midY = (opts.startFinish.y1 + opts.startFinish.y2) / 2;
  return {
    id: opts.id,
    label: opts.label,
    viewBox: opts.viewBox,
    transform: opts.transform,
    labelTransform: opts.labelTransform ?? "",
    segments: opts.infield ? [...opts.loop, opts.infield] : [...opts.loop],
    startFinish: opts.startFinish,
    centerline,
    startOffset: nearestLength(centerline, midX, midY),
  };
}

