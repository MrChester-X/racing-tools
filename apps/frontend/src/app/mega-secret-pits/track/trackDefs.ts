import { parsePoints, buildCenterline, nearestLength, Centerline } from "./trackGeometry";

export interface StartFinish {
  x1: number;
  y1: number;
  x2: number;
  y2: number;
}

export interface TrackDef {
  /** Stable identifier, used for manual selection + persistence. */
  id: string;
  /** Human-readable name shown in the track picker. */
  label: string;
  viewBox: string;
  /** Outer <g> transform from the source SVG (rotation + mirror). */
  transform: string;
  /** Counter-transform applied to kart-number labels so they read upright
   * despite `transform` (rotation/mirror). Empty when `transform` is identity. */
  labelTransform: string;
  /** All drawable track segments (raw SVG `points` strings). */
  segments: string[];
  startFinish: StartFinish;
  /** Loop centerline used to position karts by lap progress. */
  centerline: Centerline;
  /** Arc length where the start-finish line sits (lap progress 0). */
  startOffset: number;
}

